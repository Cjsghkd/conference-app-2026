private const val SPONSOR_HEADING_STROKE_WIDTH = 2f

@Composable
internal fun SponsorHeadingDecoration(
    plan: SponsorPlan,
    modifier: Modifier = Modifier,
) {
    val artwork = plan.headingArtwork
    val path = remember(artwork.pathData) {
        PathParser().parsePathString(artwork.pathData).toPath()
    }
    val color = MaterialTheme.colorScheme.onSurface

    Canvas(modifier = modifier.size(artwork.width, artwork.height)) {
        withTransform(
            transformBlock = {
                scale(
                    scaleX = size.width / artwork.width.value,
                    scaleY = size.height / artwork.height.value,
                    pivot = Offset.Zero,
                )
            },
        ) {
            drawPath(
                path = path,
                color = color,
                style = Stroke(
                    width = SPONSOR_HEADING_STROKE_WIDTH,
                    cap = StrokeCap.Round,
                ),
            )
        }
    }
}

